#!/usr/bin/env python3
"""Generate CPython frozen-module headers using the host interpreter.

This replicates Programs/_freeze_module.c so the frozen .h files can be produced
at build time rather than being committed to the repository. It must run under
CPython 3.13: the marshalled bytecode it emits has to match the interpreter
being built, and marshal/bytecode compatibility is only guaranteed within a
feature release.

The module list (and the source/alias/glob handling) is taken straight from the
repo's own Tools/build/freeze_modules.py, so this stays in step with upstream.
getpath.py is frozen separately, exactly as Makefile.pre.in does it.
"""

import marshal
import os
import sys

HEADER = "/* Auto-generated by Programs/_freeze_module.py */"


def freeze_one(name, pyfile, outpath):
    with open(pyfile, "rb") as f:
        text = f.read()
    # Matches Py_CompileStringExFlags(text, "<frozen name>", Py_file_input,
    # NULL, 0) followed by PyMarshal_WriteObjectToString(code, 4) in
    # Programs/_freeze_module.c.
    code = compile(text, "<frozen %s>" % name, "exec", flags=0,
                   dont_inherit=True, optimize=0)
    data = marshal.dumps(code, 4)
    varname = "_Py_M__" + name.replace(".", "_")
    with open(outpath, "w") as out:
        out.write(HEADER + "\n")
        out.write("const unsigned char %s[] = {\n" % varname)
        for n in range(0, len(data), 16):
            out.write("    " + "".join("%u," % b for b in data[n:n + 16]) + "\n")
        out.write("};\n")


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: freeze.py <cpython-repo> <out-dir>")
    repo_dir, out_dir = sys.argv[1], sys.argv[2]

    if sys.version_info[:2] != (3, 13):
        sys.exit("freeze.py must run under CPython 3.13, got %s"
                 % ".".join(map(str, sys.version_info[:3])))

    sys.path.insert(0, os.path.join(repo_dir, "Tools", "build"))
    import freeze_modules as fm

    outdir = os.path.join(out_dir, "Python", "frozen_modules")
    os.makedirs(outdir, exist_ok=True)

    for src in fm._iter_sources(list(fm.parse_frozen_specs())):
        freeze_one(src.frozenid, src.pyfile,
                   os.path.join(outdir, os.path.basename(src.frozenfile)))

    # getpath.py is frozen separately from freeze_modules (see Makefile.pre.in).
    freeze_one("getpath", os.path.join(repo_dir, "Modules", "getpath.py"),
               os.path.join(outdir, "getpath.h"))


if __name__ == "__main__":
    main()
